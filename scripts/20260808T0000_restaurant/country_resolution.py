#!/usr/bin/env python3
"""#1881 住所から ISO 3166-1 alpha-2 の国コードを決める。**判定はこの 1 本が正本。**

## なぜこのモジュールが要るか

`country_code` は長らく **緯度経度の矩形**（20.0〜46.5N / 122.0〜154.0E）で決めていた。
矩形は国境ではないので、朝鮮半島もウラジオストクも丸ごと `'JP'` になっていた
（dev で 98,139 行 / #1881）。

オーナー確定（#1881）:

> B で。**住所から割り出して欲しいよ。** あとちゃんとテストしてください。

## ⚠️ 判定を 2 箇所に書かない

#1881 の本当の欠陥は «矩形で決めたこと» ではなく、**同じ矩形が 7 箇所に写経され、
検証もその矩形を使っていた**ことである。作った規則と同じ規則で確かめていたので、
何を作っても緑になった。

だからここでは **順序付きの `RULES` 1 本**だけを定義し、

- Python の `country_code_from_address()`（同期・監査・テストが使う）
- BigQuery の `country_code_sql()`（`3_4_build_restaurant_catalog.py` が使う）

の両方を **そこから作る**。どちらか片方へ規則を書き足せないようにしてある。

## ⚠️ «決められない» を返せることが、この関数の一番大事な性質である

矩形の欠陥は「間違えたこと」より「**分からないのに断言したこと**」である。
手掛かりが無い住所には `None`（SQL では NULL）を返す。`country_code` は NULL 可。

## 正規表現は Python `re` と BigQuery RE2 の共通部分だけで書く

先読み・後方参照・`\\p{...}` は使わない。大文字小文字を無視したいときは
**パターン先頭の `(?i)`** で書く（`re.IGNORECASE` を使うと SQL 側へ運べない）。
"""

from __future__ import annotations

import re

# ---------------------------------------------------------------------------
# 判定の正本 — 上から順に当て、最初に当たったものを返す
# ---------------------------------------------------------------------------
#
# 並び順に意味がある:
#   1. 住所に明示された国名・国コード・行政区画（一番強い）
#   2. 文字種（ハングル / キリル）
#   3. 韓国にしか無い住所の書き方
#   4. ローマ字化された韓国の行政区画
#   5. 日本にしか無い住所の書き方
#   6. 文字種（かな・カナ） ← **一番弱い。最後の手段**
#   7. ローマ字化された日本の行政区画
#
# ⚠️ 4 / 7 は «両方の言語に出る綴りを入れない» ことだけが安全性の根拠である。
#    韓国は `-gu` / `-si`、日本は `-ku` / `-shi`。`-cho` `-machi` は日本にしか無い。
#    迷ったら **どちらの表にも入れない**（None を返すほうが、間違えるより良い）。
#
# ## #1881 «強い手掛かりが弱い手掛かりより後ろに置かれていた»（2026-09-24）
#
# 住所から引く方式に変えて誤ラベルは 85,685 → 8 行まで減ったが、**残った 8 行は
# すべて «韓国だけの手掛かりが、日本の弱い手掛かりに順番で負けた» 形だった**
# （[run 35976523693](https://github.com/Ayato-kosaka/nanitabeyo/actions/runs/35976523693)）。
#
# | 住所 | 当たっていた規則 | 本当の手掛かり |
# | --- | --- | --- |
# | `449-1001 Seonghwan-ri, Seonghwan-eup` | 日本の郵便番号 `^\d{3}-\d{4}` | `-eup`（邑） |
# | `656-1082 Seongsu-dong 1(il)-ga` | 同上 | `-dong`（洞） |
# | `中区茶洞125` | `[市区町村郡]`（中区は韓国にもある） | `茶洞125`（洞 + 番地） |
# | `Yeouido-dong, 36-2 大韓民国 ソウル …` | かな・カナ（「ソウル」） | **`大韓民国` と書いてある** |
# | `京畿道安養市東安区市民大路311金剛スマートビル208号` | かな・カナ（「スマートビル」） | **`京畿道`** |
# | `京畿道平澤市中央市場路20番キル7` | かな・カナ（「キル」） | **`京畿道`** |
#
# **欠陥は «規則が間違っていた» ことではなく «順番» である。** だから規則を足すのではなく、
# 強さの順に並べ直した。とくにかな・カナは **最も弱い**（外国の住所を片仮名で書けば
# 1 文字で日本になる）ので、日本固有の書き方より後ろへ下げた。
#
# ⚠️ **カナを «最後の手段» に下げると、カナしか手掛かりが無い住所は None になる。**
#    それが正しい（→ «決められない» を返せることが一番大事な性質、下記）。

_KR_ROMAN_SUFFIXES = ("dong", "gil", "ro", "myeon", "eup", "gu", "si")
_JP_ROMAN_SUFFIXES = ("ku", "shi", "cho", "machi", "gun", "ken", "fu", "to")


def _roman_suffix_pattern(suffixes: tuple[str, ...]) -> str:
    """`Bupyeong-dong` `Shibuya-ku` のような «語 or 数字 + ハイフン + 接尾辞» を当てる。"""
    return (
        r"(?i)(?:^|[\s,\-])[A-Za-z0-9][A-Za-z'()0-9]*-(?:"
        + "|".join(suffixes)
        + r")(?:$|[\s,.\d])"
    )


# 韓国の «道»。**日本の `道` は北海道だけ**なので、これらは韓国にしか出ない。
# ⚠️ `釜山` `仁川` のような短い市名は入れない。日本のビル名に出うる（迷ったら入れない）。
_KR_PROVINCES = (
    "京畿道",
    "江原道",
    "忠清北道",
    "忠清南道",
    "全羅北道",
    "全羅南道",
    "慶尚北道",
    "慶尚南道",
    "済州道",
    "済州特別自治道",
    "ソウル特別市",
)

RULES: tuple[tuple[str, str], ...] = (
    # --- 1. 住所に明示された国・行政区画 ---------------------------------------
    # ⚠️ 語境界で当てる。`KR` を部分一致にすると `KRAFT ビル` のような住所に当たる。
    (r"(?i)(?:^|[\s,])(?:KR|Korea|South Korea|Republic of Korea)(?:$|[\s,.])", "KR"),
    (r"대한민국|한국", "KR"),
    # #1881 漢字の「大韓民国」。`Yeouido-dong, 36-2 大韓民国 ソウル …` が
    # 「ソウル」のカナで JP になっていた。**住所に国名が書いてあるのに負けていた。**
    (r"大韓民国", "KR"),
    (r"|".join(_KR_PROVINCES), "KR"),
    (r"(?i)(?:^|[\s,])(?:JP|Japan)(?:$|[\s,.])", "JP"),
    (r"日本国?(?:$|[\s,、])", "JP"),
    (r"(?i)(?:^|[\s,])(?:RU|Russia|Russian Federation)(?:$|[\s,.])", "RU"),
    (r"Росси[яи]", "RU"),
    (r"(?i)(?:^|[\s,])(?:CN|China)(?:$|[\s,.])", "CN"),
    (r"(?i)(?:^|[\s,])(?:TW|Taiwan)(?:$|[\s,.])", "TW"),
    (r"(?i)(?:^|[\s,])(?:KP|North Korea)(?:$|[\s,.])", "KP"),
    # --- 2. 文字種（ハングル / キリル） ----------------------------------------
    (r"[가-힣]", "KR"),  # ハングル
    (r"[Ѐ-ӿ]", "RU"),  # キリル
    # --- 3. 韓国にしか無い住所の書き方 ------------------------------------------
    #
    # #1881 `中区茶洞125` が `[市区町村郡]`（中区は韓国にもある）で JP になっていた。
    # ⚠️ **`洞` 単独では当てない。** 日本にも「洞爺湖町」のような地名がある。
    #    韓国の «동» は **行政単位なので直後に番地の数字が来る**。そこだけを当てる。
    (r"[一-鿿]洞\s*[0-9０-９]", "KR"),
    # --- 4. ローマ字化された韓国の行政区画 --------------------------------------
    #
    # ⚠️ **日本の «書き方» より前に置く。** `449-1001 Seonghwan-ri, Seonghwan-eup` が
    #    日本の郵便番号 `^\d{3}-\d{4}` に当たって JP になっていた。韓国の番地は
    #    3 桁-4 桁の形を取りうるので、`-eup` `-dong` のような **韓国にしか無い接尾辞**の
    #    方が強い手掛かりである。
    (_roman_suffix_pattern(_KR_ROMAN_SUFFIXES), "KR"),
    # 「Bupyeong-dong 2(i)-ga」「beon-gil」のような番地表記
    (r"(?i)(?:\d\s*\(\s*[a-z]\s*\)\s*-\s*ga|beon-?gil)(?:$|[\s,.])", "KR"),
    # --- 5. 日本にしか無い住所の書き方 ------------------------------------------
    #
    # ⚠️ 当初は「都道府県名 + 市区町村」を要求していたが、dev の実データはそこまで
    #    書いていない行が多く（`高知市追手筋1-3-11` / `根津2-32-8`）、
    #    98,190 行が «決められない» に落ちた（run 34032307384）。
    (r"[都道府県]\s*[^\s]*[市区町村郡]", "JP"),
    (r"[^\s]{1,6}[市区町村郡][^\s]", "JP"),
    (r"丁目|番地", "JP"),
    (r"^\s*〒?\d{3}-?\d{4}", "JP"),  # 郵便番号
    (r"[一-鿿][^\s]*[0-9０-９]+[-−ー][0-9０-９]+", "JP"),
    (r"(?i)\bChome\b", "JP"),  # ローマ字の「丁目」。韓国の住所には出ない
    # --- 6. 文字種（かな・カナ）— **一番弱い。最後の手段** ----------------------
    #
    # ⚠️ 外国の住所を片仮名で書けば 1 文字で日本になってしまう。実際に
    #    `京畿道…金剛スマートビル208号` / `…中央市場路20番キル7` が「スマートビル」
    #    「キル」の 3 文字で JP になっていた。**日本固有の書き方より後ろへ下げた。**
    (r"[぀-ヿ]", "JP"),
    # --- 7. ローマ字化された日本の行政区画 --------------------------------------
    (_roman_suffix_pattern(_JP_ROMAN_SUFFIXES), "JP"),
)

_COMPILED: tuple[tuple[re.Pattern[str], str], ...] = tuple(
    (re.compile(pattern), code) for pattern, code in RULES
)


def matched_rule(address: str | None) -> tuple[int, str, str] | None:
    """当たった規則を `(RULES の添字, パターン, 国コード)` で返す。当たらなければ None。

    #1881 【設計】**«どの規則がその国コードを出したか» を機械的に引けるようにする。**

    2026-09-24 に «日本の外に居る JP» が 8 行まで減ったあと、監査は
    «作成元 / components の国» までは出せたのに **どの規則が JP と言ったのかを
    出せず、直し方を決められなかった**。規則は 25 本あり、当たった 1 本によって
    手当てが全く違う（綴りの衝突なら規則を直す / 住所が空なら同期の取りこぼし）。

    ⚠️ `country_code_from_address()` は **この関数を通して**答えを出す。
       «同じ走査を 2 回書く» を避けるため（片方だけ直す事故が起きる）。
    """
    if not address:
        return None
    text = address.strip()
    if not text:
        return None
    for index, (pattern, code) in enumerate(_COMPILED):
        if pattern.search(text):
            return index, RULES[index][0], code
    return None


def country_code_from_address(address: str | None) -> str | None:
    """住所の文字列だけから ISO 3166-1 alpha-2 を返す。決められなければ None。

    ⚠️ **緯度経度は見ない。** 座標で国を決めるのが #1881 の欠陥そのものなので、
       この関数へ座標を渡せるようにしてはいけない。
    """
    hit = matched_rule(address)
    return hit[2] if hit else None


def country_code_sql(address_expr: str) -> str:
    """同じ `RULES` から BigQuery の CASE 式を組む。

    `3_4_build_restaurant_catalog.py` がこれを埋め込む。**SQL 側へ規則を書かない。**

    Args:
        address_expr: 住所の列を指す SQL 式（例: `s.canonical_address`）
    """
    branches = "\n            ".join(
        # r'''…''' で囲むのは、パターンに `'` が入りうるため。
        f"WHEN REGEXP_CONTAINS({address_expr}, r'''{pattern}''') THEN '{code}'"
        for pattern, code in RULES
    )
    return f"CASE\n            {branches}\n          END"
