-- #745 【設計】Wikidata food nodes 抽出ロジックの 2 段階化（P31 / P279 closure）
--
-- ## 目的
-- P279* による class 階層の事前計算テーブルを作成し、
-- (wdt:P31|wdt:P279)* property path に依存しない 2 段階設計を実現する。
--
-- ## 処理内容
-- 1. food_class_closure: クラス閉包テーブル作成
--    - 各 root_qid に対して P279* で到達可能な全クラス QID を保持
--    - インスタンス数よりも遥かに少ないクラス階層のみを扱う
--
-- ## 使い方
-- スクリプト側から ${DATASET} をプレースホルダ置換して実行される。
--
-- ## 注意
-- - テーブルは CREATE TABLE IF NOT EXISTS で作成されるため、再実行可能
-- - データ投入は Python スクリプト側で行う
-- ==============================================================================


-- -----------------------------------------------------------------------------
-- food_class_closure: クラス閉包テーブル
-- -----------------------------------------------------------------------------
-- 各 food_roots の root_qid に対して、P279* で到達可能な全クラス QID を保持
-- これにより fetch_food_nodes では P31-only クエリが可能となり、
-- WDQS への負荷を大幅に削減できる
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `${DATASET}.food_class_closure` (
  class_qid  STRING NOT NULL,   -- P279* で root に到達可能なクラス QID
  root_qid   STRING NOT NULL,   -- 元の root QID (food_roots.root_qid)
  kind       STRING NOT NULL,   -- root の kind (food_roots.kind より継承)
  depth      INT64  NOT NULL    -- root までの距離 (0=root 自身, 1=直接 subclass, ...)
);

-- インデックス的な意味でのクラスタリング（任意）
-- class_qid をプライマリにすることで、P31 クエリ時の VALUES 展開が効率的になる
