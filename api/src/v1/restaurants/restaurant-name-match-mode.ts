/*
このファイルの責務
- 店名検索の `q` を、**`name ILIKE '%q%'`（中間一致）で引いてよいか**だけを判定する。
  SQL は組み立てない（組み立ては `restaurants.repository.ts`）。

## なぜ判定が要るのか — 2 文字で本番 20 秒（#1951）

`restaurants` は約 57 万行。店名検索は GIN trigram 索引 `idx_restaurants_name_trgm` で引くが、
**pg_trgm は LIKE のパターンから trigram（3 文字）を取り出せないと索引を使えない。**

pg_trgm はパターンを `%` で区切った各語について、**先頭なら空白 2 つ・末尾なら空白 1 つ**を
足してから trigram を取る。したがって:

| パターン | 取れる trigram | プラン |
| --- | --- | --- |
| `%一蘭%` | **0 個**（両端が `%` なので 2 文字からは作れない） | **Seq Scan** |
| `一蘭%` | `"  一"` `" 一蘭"` の 2 個 | Bitmap Index Scan |
| `% 一蘭%` | 同上（空白が左パディングの役をする） | Bitmap Index Scan |

Seq Scan は 57 万行の**太い行**（`address_components` JSONB）をリモートストレージから
全部読むので、本番で **20.34 秒**かかっていた（`一蘭` / 半径 1,500km。2026-09-09 実測）。
ローカル SSD・薄い行なら同じ Seq Scan でも 0.42 秒なので、**行の太さとストレージが効いている**。

⚠️ かつては «エリア内検索だから破綻しない» が安全弁だった。#1629 で店名検索の半径を
   «地図の表示範囲» から **全国 1,500km** へ広げたときに、その前提が外れた。

## 「3 文字以上か」ではなく「連続する語が 3 文字以上か」

⚠️ **単純な `length >= 3` にしないこと。** pg_trgm が見るのは «パターンの中の連続した文字列» で、
   空白で切れていると別の語になる。逆に**語が 2 つ以上あれば、2 語目以降に左パディングが付く**ので
   1 文字ずつでも trigram は取れる（`一 蘭` → `" 蘭"` … ）。

したがって判定は「語に分けて、**語が 2 つ以上** または **唯一の語が 3 文字以上**」になる。

## 安全な向きへ倒す

語文字の定義（`\p{L}` / `\p{N}`）は DB 側の locale と多少ずれうる。ずれても
**危険な向き（索引が効かないのに中間一致を選ぶ）には倒れない**ようにしてある。

- 語が 2 つあると判定したなら、pg 側でも語は 2 つ以上か 1 つの長い語なので、必ず trigram が取れる
- TS が 3 文字と数えたもの（コードポイント単位）は、pg 側でも 3 文字以上か複数語になる

⚠️ **`length` ではなく `Array.from()` で数えること。** サロゲートペア（絵文字・一部の漢字）を
   2 文字と数えると、1 文字の入力を «3 文字以上» と誤判定して Seq Scan を許してしまう。
*/

/** 語の区切り。文字でも数字でもないものはすべて区切りとして扱う */
const NON_WORD = /[^\p{L}\p{N}]+/u;

/**
 * `name ILIKE '%q%'`（中間一致）で引いてよいか。
 *
 * `false` のときは呼び出し側が**前方一致 / 語頭一致**へ切り替える
 * （`restaurants.repository.ts` の `buildNameFilter`）。
 *
 * @param query エスケープ**前**の生の検索語。空白のトリムは呼び出し側で済んでいる想定
 */
export function isSubstringIndexable(query: string): boolean {
	const words = query.split(NON_WORD).filter((word) => word.length > 0);
	if (words.length === 0) return false;
	if (words.length >= 2) return true;
	// コードポイントで数える（サロゲートペアを 2 文字と数えない）
	return Array.from(words[0]).length >= 3;
}
