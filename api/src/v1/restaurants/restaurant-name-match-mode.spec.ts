/*
#1951 «索引が効かない検索語 × 全国半径» を二度と作らないための回帰テスト。

守るのは **«中間一致で引いてよい» の判定そのもの**であって、個別の店名ではない
（CLAUDE.md「完了の定義」§5: 回帰テストはパターンに対して書く）。

本番で `一蘭` / 半径 1,500km が **20.34 秒**かかっていた（2026-09-09 実測）。
真因は pg_trgm が `%一蘭%` から trigram（3 文字）を取り出せず、57 万行の太い行を
Seq Scan していたこと。判定の根拠は `restaurant-name-match-mode.ts` の JSDoc にある。
*/
import { isSubstringIndexable } from './restaurant-name-match-mode';

describe('#1951 isSubstringIndexable — 中間一致で trgm 索引に乗るか', () => {
  /*
    ⚠️ **ここが false になるものは、中間一致で引くと Seq Scan になる。**
    「短いから使われないだろう」で通してはいけない。2 文字の店名は普通に実在する
    （一蘭・魚金・鳥貴・磯丸）。
  */
  it.each([
    ['一蘭', '2 文字。本番で 20.34 秒かかった実物'],
    ['魚金', '2 文字'],
    ['す', '1 文字。本番ログで 20.1 秒'],
    ['らー', '2 文字（長音を含む）'],
    ['A1', '英数 2 文字'],
    ['🍣', 'サロゲートペア 1 文字。length では 2 と数えられる'],
    ['  ', '空白だけ。語がゼロ'],
  ])('%s は中間一致で引かない（%s）', (query) => {
    expect(isSubstringIndexable(query)).toBe(false);
  });

  /*
    ⚠️ 逆に、ここが true になるものを false へ倒すと **語中一致を無駄に捨てる**。
    pg_trgm が見るのは «連続した語» なので、語が 2 つあれば 1 文字ずつでも
    2 語目に左パディングが付いて trigram が取れる。
  */
  it.each([
    ['八王子', '3 文字'],
    ['すりー', '3 文字'],
    ['一 蘭', '1 文字 + 1 文字。語が 2 つあるので trigram が取れる'],
    ['一　蘭', '全角空白区切り'],
    ['A B', '英字 1 文字 × 2 語'],
    ['八王子ラーメンよしだ', '長い店名'],
  ])('%s は中間一致で引いてよい（%s）', (query) => {
    expect(isSubstringIndexable(query)).toBe(true);
  });

  /*
    #1951 **サロゲートペアを 2 文字と数えない。**
    `'🍣'.length === 2` なので、`length >= 3` で判定すると `🍣鮨` のような入力が
    «3 文字以上» に化けて Seq Scan を許す。コードポイントで数えることを固定する。
  */
  it('サロゲートペアを 2 文字と数えない（length で判定しない）', () => {
    expect('🍣鮨'.length).toBe(3); // UTF-16 の単位ではこう見える
    expect(isSubstringIndexable('🍣鮨')).toBe(false); // 実際は «絵文字 + 1 文字の語» なので乗せない
  });

  /*
    #1951 **絵文字・記号は «語の区切り» として扱われる**（`\p{L}` でも `\p{N}` でもない）。
    そのため `🍣鮨屋` は «2 文字の語が 1 つ» と数えられ、中間一致には乗せない。

    ⚠️ これは**安全な向きの誤り**である。実際には pg 側で trigram が取れる可能性もあるが、
       取れないほうへ倒しておけば Seq Scan にはならない。逆向き（乗せてしまう）に倒すと
       本番 20 秒が復活する。判定がずれてよいのはこの向きだけ。
  */
  it('絵文字は語の区切りとして扱い、安全な側へ倒す', () => {
    expect(isSubstringIndexable('🍣鮨屋')).toBe(false); // 語は «鮨屋» の 2 文字だけ
    expect(isSubstringIndexable('🍣鮨屋台')).toBe(true); // 語が 3 文字になれば乗る
  });
});
